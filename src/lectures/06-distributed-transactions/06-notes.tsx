            <section>
                <h2>Хореография и оркестрация распределяют управление</h2>
                <p>
                    Сагу можно координировать хореографией или оркестрацией. Это
                    два способа определить, кто решает, какой шаг выполнить
                    дальше и как реагировать на ошибку.
                </p>
                <h3>Хореография</h3>
                <p>
                    При хореографии нет центрального координатора. Сервис,
                    завершивший локальный шаг, публикует событие, а другой
                    сервис подписывается на него и запускает следующий шаг.
                    Например, создание заказа публикует событие «ЗаказСоздан»,
                    платёжный сервис реагирует на него и после списания
                    публикует «ПлатёжПроведён», на которое реагирует склад.
                </p>
                <p>
                    Такая схема позволяет сервисам взаимодействовать через
                    события и не требует, чтобы один компонент вызывал всех
                    остальных напрямую. Однако последовательность процесса
                    распределена между обработчиками. Когда событий и ветвлений
                    становится много, труднее увидеть весь процесс, определить,
                    где он остановился, и убедиться, что каждый путь ошибки
                    приводит к нужным компенсациям. Нужны общие правила
                    корреляции событий, владения шагами и наблюдения за
                    незавершёнными операциями.
                </p>
                <h3>Оркестрация</h3>
                <p>
                    При оркестрации отдельный координатор хранит состояние саги
                    и явно запускает действия: создать заказ, провести платёж,
                    зарезервировать товар. Если шаг не удался, координатор
                    выбирает следующую команду — например, повторить действие,
                    запустить компенсацию или завершить процесс с ошибкой.
                    Правила одной бизнес-операции собраны в одном месте, и её
                    путь проще проследить.
                </p>
                <p>
                    Координатор не должен быть единственной копией состояния.
                    Если он упадёт, процесс должен восстановиться из надёжно
                    сохранённой записи. До запуска внешнего шага координатор
                    сохраняет начало саги, текущий этап и намерение выполнить
                    действие; после получения результата фиксирует его и
                    продвигает процесс. Иначе сбой между отправкой команды и
                    записью ответа оставит неизвестным, выполнился ли шаг.
                </p>
                <p>
                    Запись состояния и отправка команды в другой сервис — два
                    действия в разных системах. Если координатор сначала
                    сохранит состояние, а затем упадёт до отправки, команда не
                    дойдёт. Если сначала отправит, а потом упадёт до сохранения,
                    после перезапуска он может отправить команду повторно.
                    Частое решение этой проблемы — transactional outbox:
                    координатор одной локальной транзакцией сохраняет новое
                    состояние саги и сообщение-команду в таблицу исходящих
                    сообщений, а отдельный процесс доставляет команду и отмечает
                    её отправленной. Получатель всё равно должен выдерживать
                    повторы идемпотентно.
                </p>
            </section>

